const CATALOG: Record<NativeLocale, Record<NativeMessageKey, string>> = { en: EN, "pt-BR": PT_BR };

let activeLocale: NativeLocale = "en";

export function resolveNativeLocale(systemLocale: string): NativeLocale {
  return /^pt(-|$)/i.test(systemLocale) ? "pt-BR" : "en";
}

export function setNativeLocale(next: NativeLocale): void {
  activeLocale = next;
}

export function nativeMessage(key: NativeMessageKey, params?: Record<string, string>): string {
  const template = CATALOG[activeLocale][key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => params[name] ?? match);
}
